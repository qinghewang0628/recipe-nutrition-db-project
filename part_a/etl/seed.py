"""Write psql loaders, the output manifest and raw checksums."""
from __future__ import annotations

import json
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from . import config as C
from . import io_utils as U

# Adjust TABLE_MAP here if the schema uses different table names
TABLE_MAP = {
    "recipes": "recipes",
    "ingredients": "ingredients",
    "nutrition": "nutrition",
    "steps": "steps",
    "cuisines": "cuisines",
    "cuisine_category": "cuisine_category",
    "recipe_allergens": "recipe_allergens",
    "recipe_dietary_audit": "recipe_dietary_audit",
    "ingredient_master": "ingredient_master",
    "ingredient_stats": "ingredient_stats",
    "recipe_search_document": "recipe_search_document",
}


def _load_sql(tables: list[str], prefix: Path) -> str:
    L = [
        "-- Generated by etl/seed.py. Do not edit.",
        "-- Prerequisite: the schema.sql tables already exist.",
        "-- Run from the repository root: psql \"$DATABASE_URL\" -f sql/load_clean.sql",
        "-- \\copy is a psql client command; paths are relative to the working directory.",
        "\\set ON_ERROR_STOP on",
        "BEGIN;",
        "",
    ]
    for t in tables:
        p = (prefix / f"{t}.csv").as_posix().replace("\\", "/")
        rel = p.replace(str(C.ROOT.as_posix()).rstrip("/") + "/", "")
        L.append(f"\\copy {TABLE_MAP[t]} FROM '{rel}' WITH (FORMAT csv, HEADER true, ENCODING 'UTF8')")
    L += ["", "COMMIT;", ""]
    return "\n".join(L)


def _file_entry(p: Path) -> dict[str, Any]:
    return {
        "path": str(p.relative_to(C.ROOT)).replace("\\", "/"),
        "bytes": p.stat().st_size,
        "rows": sum(1 for _ in open(p, "r", encoding="utf-8-sig", newline="")) - 1,
        "sha256": U.sha256(p),
    }


def build(scales: dict[str, Any] | None = None, verbose: bool = True) -> dict[str, Any]:
    C.SQL.mkdir(parents=True, exist_ok=True)
    U.write_text(C.SQL / "load_clean.sql", _load_sql(C.CLEAN_TABLES, C.CLEAN))
    for s in C.SCALE_ORDER:
        U.write_text(C.SQL / f"load_{s}.sql", _load_sql(C.SCALE_TABLES, C.SCALES / s))

    raw_dir = C.raw_dir()
    lines = [f"{U.sha256(raw_dir / fn)}  {fn}" for fn in C.RAW_FILES.values()]
    U.write_text(C.DATA / "raw" / "MANIFEST.sha256", "\n".join(lines) + "\n")

    manifest: dict[str, Any] = {
        "project": "Smart Recipe and Nutrition Retrieval System / DSC5003 Group Project / Person A (Data Engineering)",
        "generated_at_utc": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "generator": "python -m etl.pipeline all  (make seed)",
        "python_stdlib_only": True,
        "config": {
            "random_seed": C.RANDOM_SEED,
            "scale_factors": C.SCALE_FACTORS,
            "cap_g_per_serving": C.CAP_G_PER_SERVING,
            "dietary_flags": C.DIETARY_FLAGS,
            "halal_verifiable": C.HALAL_VERIFIABLE,
            "placeholder_codes": sorted(set(C.PLACEHOLDER_CODES.values())),
        },
        "raw_input": {
            # Keep the manifest portable: record the directory name, not an
            # absolute path that would leak a local machine layout.
            "directory": raw_dir.name,
            "files": {fn: {"sha256": U.sha256(raw_dir / fn),
                           "bytes": (raw_dir / fn).stat().st_size,
                           "matches_expected": U.sha256(raw_dir / fn) == C.RAW_SHA256[fn]}
                      for fn in C.RAW_FILES.values()},
        },
        "mappings": {p.name: _file_entry(p) for p in sorted(C.MAPPINGS.glob("*.csv"))},
        "clean": {t: _file_entry(C.CLEAN / f"{t}.csv") for t in C.CLEAN_TABLES},
        # verification.json is rewritten by STEP 8 and excluded from the manifest
        "profile": {p.name: {"path": str(p.relative_to(C.ROOT)).replace("\\", "/"),
                             "sha256": U.sha256(p)}
                    for p in sorted(C.PROFILE.iterdir())
                    if p.is_file() and p.name != "verification.json"},
        "scales": scales or {},
        "sql": {p.name: {"path": str(p.relative_to(C.ROOT)).replace("\\", "/"),
                         "sha256": U.sha256(p)} for p in sorted(C.SQL.glob("*.sql"))},
        "load_order": C.CLEAN_TABLES,
        "note": "small is the cleaned baseline; medium/large are seeded synthetic expansions for index scalability only.",
    }
    U.write_json(C.DATA / "manifest.json", manifest)
    if verbose:
        U.log(f"Wrote sql/load_*.sql, data/manifest.json, data/raw/MANIFEST.sha256")
    return manifest
